// Writing Rocq: the generated table file and observation files.

func rocqSort(s tcheck.Sort) string {
	switch s.Kind {
	case tcheck.SortVal:
		return "SVal"
	case tcheck.SortType:
		return "SType"
	}
	return fmt.Sprintf("(SU %d)", s.Num)
}

func rocqList[A any](f func(A) string, l []A) string {
	var parts []string
	for _, x := range l {
		parts = append(parts, f(x))
	}
	return "[" + strings.Join(parts, "; ") + "]"
}

func rocqTerm(t *tcheck.Term) string {
	switch t.Kind {
	case tcheck.TVar:
		return fmt.Sprintf("(TVar %d)", t.Num)
	case tcheck.TSym:
		return fmt.Sprintf("(TSym %d %s)", t.Num, rocqList(rocqTerm, t.Args))
	case tcheck.TPair:
		return "(TPair " + rocqTerm(t.Args[0]) + " " + rocqTerm(t.Args[1]) + ")"
	case tcheck.TLit:
		return "(TLit " + rocqTerm(t.Args[0]) + " " + rocqList(rocqTerm, t.Args[1:]) + ")"
	}
	return "TUnit"
}

func rocqPat(p *tcheck.Pat) string {
	if p.Kind == tcheck.PVal {
		return "(PVal " + rocqTerm(p.T) + ")"
	}
	return "(PApp " + rocqPat(p.A) + " " + rocqPat(p.B) + ")"
}

func rocqAtom(a *tcheck.Atom) string {
	if a.Kind == tcheck.APred {
		return fmt.Sprintf("(APred %d %s)", a.Num, rocqList(rocqTerm, a.Args))
	}
	return "(AEq " + rocqTerm(a.Args[0]) + " " + rocqTerm(a.Args[1]) + ")"
}

func rocqStr(x string) string { return "\"" + strings.ReplaceAll(x, "\"", "\"\"") + "\"%go" }

func rocqExpr(e *tcheck.Expr) string {
	switch e.Kind {
	case tcheck.EVal:
		return "(CVal " + rocqTerm(e.T) + ")"
	case tcheck.EVar:
		return "(CVar " + rocqStr(e.Name) + ")"
	case tcheck.EApp:
		return "(CApp " + rocqExpr(e.A) + " " + rocqExpr(e.B) + ")"
	case tcheck.EPair:
		return "(CPair " + rocqExpr(e.A) + " " + rocqExpr(e.B) + ")"
	case tcheck.ELet:
		return "(CLet " + rocqStr(e.Name) + "\n  " + rocqExpr(e.A) + "\n  " + rocqExpr(e.B) + ")"
	case tcheck.ESeq:
		return "(CSeq " + rocqExpr(e.A) + "\n  " + rocqExpr(e.B) + ")"
	case tcheck.ELit:
		return "(CLit " + rocqTerm(e.T) + " " + rocqList(rocqExpr, e.Elems) + ")"
	case tcheck.EDo:
		return "(CDo " + rocqExpr(e.A) + ")"
	case tcheck.ERet:
		return "(CRet " + rocqExpr(e.A) + ")"
	case tcheck.EXSeq:
		return "(CXSeq " + rocqExpr(e.A) + "\n  " + rocqExpr(e.B) + ")"
	case tcheck.EXDo:
		return "(CXDo " + rocqExpr(e.A) + ")"
	}
	panic("rocqExpr")
}

func rocqRule(r *tcheck.Rule) string {
	return "mkRule " + rocqList(rocqSort, r.Vars) + "\n    " + rocqPat(r.Lhs) + "\n    " +
		rocqList(rocqAtom, r.Pre) + " " + rocqList(rocqSort, r.Ex) + " " + rocqTerm(r.Ret) + "\n    " +
		rocqList(rocqAtom, r.Post)
}

func rocqSpec(sp *tcheck.Spec) string {
	return fmt.Sprintf("mkSpec %s\n    %s\n    %s\n    %s %s\n    %s",
		rocqList(rocqSort, sp.Vars), rocqList(rocqTerm, sp.Args), rocqList(rocqAtom, sp.Pre),
		rocqList(rocqSort, sp.Ex), rocqTerm(sp.Ret), rocqList(rocqAtom, sp.Post))
}

func rocqFact(f *tcheck.Fact) string {
	return "mkFact " + rocqList(rocqSort, f.Vars) + "\n    " + rocqTerm(f.Lhs) + "\n    " + rocqTerm(f.Rhs)
}

// modulePath turns new/a/b.v into New.a.b.
func modulePath(path string) string {
	p := filepath.ToSlash(strings.TrimSuffix(path, ".v"))
	p = strings.TrimPrefix(p, "./")
	if strings.HasPrefix(p, "new/") {
		p = "New/" + strings.TrimPrefix(p, "new/")
	} else if strings.HasPrefix(p, "src/") {
		p = "Perennial/" + strings.TrimPrefix(p, "src/")
	}
	return strings.ReplaceAll(p, "/", ".")
}

const ambientArgs = "(ext : ffi_syntax) (ffi : ffi_model) (ffi_interp0 : ffi_interp ffi)\n    " +
	"(Σ : gFunctors) (hG : heapGS Σ) (ffi_semantics0 : ffi_semantics ext ffi) (sem : go.Semantics)"

const ambientBinders = "{ext : ffi_syntax} {ffi : ffi_model} {ffi_interp0 : ffi_interp ffi}\n  " +
	"{Σ : gFunctors} {hG : heapGS Σ} {ffi_semantics0 : ffi_semantics ext ffi}\n  {sem : go.Semantics}"

func (t *table) gallinaSort(name string) string {
	switch name {
	case "val":
		return "goose_lang.val"
	case "type":
		return "go.type"
	}
	for _, s := range t.sorts {
		if s.name == name {
			return "(" + s.rocq + ")"
		}
	}
	return "?"
}

func (t *table) arrowType(args []string, res string) string {
	var parts []string
	for _, a := range args {
		parts = append(parts, t.gallinaSort(a))
	}
	parts = append(parts, res)
	return strings.Join(parts, " → ")
}

// genTable writes the table file: the syntax of every symbol, predicate,
// rule and fact, and the denotation.
func (t *table) genTable(src string, cmd string) (string, error) {
	syms, err := t.symDecls()
	if err != nil {
		return "", err
	}
	preds, err := t.predDecls()
	if err != nil {
		return "", err
	}
	T := t.name
	var b strings.Builder
	fmt.Fprintf(&b, "(* Generated by gocheck/tcheck from %s -- DO NOT EDIT.\n\n     %s\n\n", src, cmd)
	b.WriteString("   The syntax of the table (what the Go checker reads) and its denotation\n" +
		"   (what each symbol and predicate means, in Gallina).  The rules and facts\n" +
		"   are proved valid by hand, in the link file next to this one. *)\n")
	for _, r := range t.requires {
		fmt.Fprintf(&b, "Require Export %s.\n", r)
	}
	b.WriteString("From New.tcheck Require Export link.\n")
	b.WriteString("\n(** Sorts:")
	for i, s := range t.sorts {
		fmt.Fprintf(&b, " [SU %d] = %s ([%s])%s", i, s.name, s.rocq, map[bool]string{true: ".", false: ";"}[i == len(t.sorts)-1])
	}
	b.WriteString(" *)\n\n")
	fmt.Fprintf(&b, "Definition %s_syms : list symdecl := [\n", T)
	for i, d := range syms {
		sep := ";"
		if i == len(syms)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "  (* %d %s *) mkSym %s %s%s\n", i, t.syms[i].name, rocqList(rocqSort, d.Args), rocqSort(d.Res), sep)
	}
	b.WriteString("].\n\n")
	fmt.Fprintf(&b, "Definition %s_preds : list preddecl := [\n", T)
	for i, d := range preds {
		sep := ";"
		if i == len(preds)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "  (* %d %s *) mkPred %v %s%s\n", i, t.preds[i].name, d.Pers, rocqList(rocqSort, d.Args), sep)
	}
	b.WriteString("].\n\n")
	for _, rd := range t.rules {
		r, err := t.rule(rd)
		if err != nil {
			return "", fmt.Errorf("rule %s: %v", rd.name, err)
		}
		fmt.Fprintf(&b, "Definition %s_rule_%s : trule :=\n  %s.\n\n", T, rd.name, rocqRule(r))
	}
	for _, fd := range t.facts {
		f, err := t.fact(fd)
		if err != nil {
			return "", fmt.Errorf("fact %s: %v", fd.name, err)
		}
		fmt.Fprintf(&b, "Definition %s_fact_%s : tfact :=\n  %s.\n\n", T, fd.name, rocqFact(f))
	}
	var moduleTypes []string
	for _, fd := range t.funcs {
		sp, err := t.spec(fd)
		if err != nil {
			return "", fmt.Errorf("func %s: %v", fd.name, err)
		}
		r, err := t.funcRule(fd)
		if err != nil {
			return "", fmt.Errorf("func %s: %v", fd.name, err)
		}
		fmt.Fprintf(&b, "(** [%s]: its specification, and the rule callers use. *)\n", fd.impl)
		fmt.Fprintf(&b, "Definition %s_spec_%s : tspec :=\n  %s.\n", T, fd.name, rocqSpec(sp))
		fmt.Fprintf(&b, "Definition %s_rule_%s : trule :=\n  spec_rule %s %s_spec_%s.\n\n", T, fd.name,
			rocqTerm(patHeadTerm(r.Lhs)), T, fd.name)
		moduleTypes = append(moduleTypes, fd.name)
	}
	b.WriteString("Section den.\n")
	fmt.Fprintf(&b, "Context %s\n  {package_sem : %s}.\n\n", ambientBinders, t.assumptions)
	fmt.Fprintf(&b, "Definition %s_sort (n : nat) : Type :=\n  match n with\n", T)
	for i, s := range t.sorts {
		fmt.Fprintf(&b, "  | %d%%nat => %s\n", i, s.rocq)
	}
	b.WriteString("  | _ => unit\n  end.\n\n")
	fmt.Fprintf(&b, "Definition %s_sym (n : nat) : sym_ty %s_sort (lookup_sym %s_syms n) :=\n", T, T, T)
	fmt.Fprintf(&b, "  match n return sym_ty %s_sort (lookup_sym %s_syms n) with\n", T, T)
	for i, s := range t.syms {
		fmt.Fprintf(&b, "  | %d%%nat => ((%s) : %s) (* %s *)\n", i, s.rocq, t.arrowType(s.args, t.gallinaSort(s.res)), s.name)
	}
	b.WriteString("  | _ => #()\n  end.\n\n")
	fmt.Fprintf(&b, "Definition %s_pred (n : nat) : pred_ty %s_sort (lookup_pred %s_preds n) :=\n", T, T, T)
	fmt.Fprintf(&b, "  match n return pred_ty %s_sort (lookup_pred %s_preds n) with\n", T, T)
	for i, p := range t.preds {
		fmt.Fprintf(&b, "  | %d%%nat => ((%s) : %s) (* %s *)\n", i, p.rocq, t.arrowType(p.args, "iProp Σ"), p.name)
	}
	b.WriteString("  | _ => True%I\n  end.\nEnd den.\n\n")
	fmt.Fprintf(&b, "Definition %s_den : den %s_syms %s_preds :=\n", T, T, T)
	fmt.Fprintf(&b, "  mkDen _ _ (λ ext ffi ffi_interp0 Σ hG ffi_semantics0 sem, %s)\n", t.assumptions)
	fmt.Fprintf(&b, "    (λ ext ffi ffi_interp0 Σ hG ffi_semantics0 sem (pkg : %s),\n       mkDenAt _ _ %s_sort %s_sym %s_pred).\n\n", t.assumptions, T, T, T)
	names := []string{T + "_den", T + "_sym", T + "_sort", T + "_pred", T + "_syms", T + "_preds"}
	for _, rd := range t.rules {
		names = append(names, T+"_rule_"+rd.name)
	}
	for _, fd := range t.facts {
		names = append(names, T+"_fact_"+fd.name)
	}
	for _, fd := range t.funcs {
		names = append(names, T+"_spec_"+fd.name, T+"_rule_"+fd.name)
	}
	fmt.Fprintf(&b, "(** Unfold the table's definitions (before [tc_simp]). *)\nLtac %s_unfold :=\n  unfold %s.\n", T, strings.Join(names, ", "))
	for _, name := range moduleTypes {
		U, N := strings.ToUpper(T), strings.ToUpper(name)
		fmt.Fprintf(&b, "\n(** The specification of [%s] as a rule, for postulates to [Include]. *)\n", name)
		fmt.Fprintf(&b, "Module Type %s_RULE_%s.\n  Parameter %s_rule_%s_ok : rule_valid %s_den %s_rule_%s.\nEnd %s_RULE_%s.\n",
			U, N, T, name, T, T, name, U, N)
	}
	return b.String(), nil
}

// genObservation writes the observation file of one run.
func genObservation(t *table, tableFile string, f *funcDecl, inp *tcheck.Input, ruleNames, factNames []string,
	bytes string, cmd string, implName string, head *tcheck.Term) string {
	T := t.name
	F := f.name
	var b strings.Builder
	fmt.Fprintf(&b, "(* Generated by gocheck/tcheck -- DO NOT EDIT.\n\n     %s\n\n", cmd)
	fmt.Fprintf(&b, "   tcheck.Check answered true on the bytes in [%s_check_run], the input\n", F)
	fmt.Fprintf(&b, "   [%s_input]: the function %s, its specification, and the rules and\n", F, f.impl)
	b.WriteString("   facts of the table that the run used.  The axiom is an observation, of\n" +
		"   the form new/tcheck/observe.v describes; gocheck/tcheck/observe.sh\n" +
		"   reruns the checker on these bytes and regenerates this file. *)\n")
	b.WriteString("From New.tcheck Require Import observe.\n")
	fmt.Fprintf(&b, "Require Import %s.\n\n", modulePath(tableFile))
	fmt.Fprintf(&b, "Definition %s_func : cfunc :=\n  mkFunc %s\n  %s.\n\n", F, rocqList(rocqStr, inp.Fn.Params), rocqExpr(inp.Fn.Body))
	var rs, fs []string
	for _, n := range ruleNames {
		rs = append(rs, T+"_rule_"+n)
	}
	for _, n := range factNames {
		fs = append(fs, T+"_fact_"+n)
	}
	fmt.Fprintf(&b, "Definition %s_rules : list trule := [%s].\n", F, strings.Join(rs, "; "))
	fmt.Fprintf(&b, "Definition %s_facts : list tfact := [%s].\n\n", F, strings.Join(fs, "; "))
	fmt.Fprintf(&b, "Definition %s_input : tinput :=\n  mkInput %s_syms %s_preds %s_rules %s_facts %s_func %s_spec_%s.\n\n", F, T, T, F, F, F, T, F)
	b.WriteString("(** OBSERVE-EXECUTION: tcheck.Check returned true on exactly these bytes. *)\n")
	fmt.Fprintf(&b, "Axiom %s_check_run : observed_run\n  %s.\n\n", F, rocqStr(bytes))
	fmt.Fprintf(&b, "Lemma %s_holds : input_holds %s_input.\n", F, F)
	fmt.Fprintf(&b, "Proof. eapply observed_input_holds; [|exact %s_check_run]. vm_compute. reflexivity. Qed.\n\n", F)
	fmt.Fprintf(&b, "(** The checked function is Goose's. *)\n")
	fmt.Fprintf(&b, "Lemma %s_func_val %s\n    (pkg : %s) :\n", F, ambientArgs, t.assumptions)
	fmt.Fprintf(&b, "  func_val (%s_den.(d_at) ext ffi ffi_interp0 Σ hG ffi_semantics0 sem pkg) %s_func =\n    %s.\n", T, F, implName)
	b.WriteString("Proof. vm_compute. reflexivity. Qed.\n\n")
	fmt.Fprintf(&b, "(** The call [%s_rule_%s] is about unfolds to the checked function. *)\n", T, F)
	fmt.Fprintf(&b, "Lemma %s_call_ok : call_ok %s_den %s_func %s_spec_%s %s.\n", F, T, F, T, F, rocqTerm(head))
	fmt.Fprintf(&b, "Proof. call_ok_by %s_func_val %s_unfold uconstr:(%s). Qed.\n", F, T, t.assumptions)
	return b.String()
}

// patHeadTerm is the value at the head of an application pattern.
func patHeadTerm(p *tcheck.Pat) *tcheck.Term {
	for p.Kind == tcheck.PApp {
		p = p.A
	}
	return p.T
}
