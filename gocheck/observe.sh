#!/usr/bin/env bash
# Runs gocheck on Median3 with the specification of demo.sh and records the
# checker input it hands to checker.Check as Lean definitions, in
#
#   Checkers/Checker/Examples/Observed/Median3Input.lean
#
# That file is the input of the axiom `median3_check_run` (Median3.lean next
# to it), which asserts that checker.Check, run on exactly this input, returns
# true. This script is the evidence for the axiom: it fails unless the checker
# answers true.
#
# Run from the repository root: bash gocheck/observe.sh
set -euo pipefail

if [ ! -d .lake/packages/perennial ]; then
	echo "missing .lake/packages/perennial (go.mod's replacement for perennial):" >&2
	echo "run 'lake build' first, which fetches the Lake dependencies" >&2
	exit 2
fi

OUT=Checkers/Checker/Examples/Observed/Median3Input.lean
MEDIAN_POST='(⌜b <u a⌝ ∗ ⌜c <u b⌝ ∗ ⌜ret == b⌝) ∨ (⌜b >=u a⌝ ∗ ⌜c >=u b⌝ ∗ ⌜ret == b⌝) ∨ (⌜c >=u b⌝ ∗ ⌜c <u a⌝ ∗ ⌜ret == c⌝) ∨ (⌜c >=u a⌝ ∗ ⌜c <u b⌝ ∗ ⌜ret == c⌝) ∨ (⌜b <u a⌝ ∗ ⌜c >=u a⌝ ∗ ⌜ret == a⌝) ∨ (⌜c <u a⌝ ∗ ⌜b >=u a⌝ ∗ ⌜ret == a⌝) ∨ (⌜b <u a⌝ ∗ ⌜a <u b⌝) ∨ (⌜b >=u a⌝ ∗ ⌜b <u a⌝)'

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
log=$(go run ./gocheck -pkg ./checker/examples -post "$MEDIAN_POST" -lean "$tmp" Median3)
echo "$log" | grep '^checker.Check:'
echo "$log" | grep -q '^checker.Check: true ' || { echo "observe.sh: checker.Check did not answer true" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
{
  echo "/- Generated by gocheck/observe.sh from"
  echo
  echo "     gocheck -pkg ./checker/examples -post <MEDIAN_POST> -lean <file> Median3"
  echo
  echo "   with the postcondition of gocheck/demo.sh: the input gocheck hands to"
  echo "   checker.Check, which answered true. Do not edit. -/"
  echo "import Checkers.Checker.Defs"
  echo
  echo "namespace Perennial"
  echo "namespace Checker"
  echo
  cat "$tmp"
  echo
  echo "end Checker"
  echo "end Perennial"
} > "$OUT"
echo "wrote $OUT"
