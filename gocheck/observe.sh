#!/usr/bin/env bash
# Runs gocheck on Median3 with the specification of demo.sh and records the
# checker input it hands to checker.Check as Rocq definitions, in
#
#   new/proof/github_com/mit_pdos/perennial/checker/examples/observed/median3_input.v
#
# That file is the input of the axiom [median3_check_run] (median3.v next to
# it), which asserts that checker.Check, run on exactly this input, returns
# true. This script is the evidence for the axiom: it fails unless the checker
# answers true.
#
# Run from the repository root: bash gocheck/observe.sh
set -euo pipefail

OUT=new/proof/github_com/mit_pdos/perennial/checker/examples/observed/median3_input.v
MEDIAN_POST='(⌜b <u a⌝ ∗ ⌜c <u b⌝ ∗ ⌜ret == b⌝) ∨ (⌜b >=u a⌝ ∗ ⌜c >=u b⌝ ∗ ⌜ret == b⌝) ∨ (⌜c >=u b⌝ ∗ ⌜c <u a⌝ ∗ ⌜ret == c⌝) ∨ (⌜c >=u a⌝ ∗ ⌜c <u b⌝ ∗ ⌜ret == c⌝) ∨ (⌜b <u a⌝ ∗ ⌜c >=u a⌝ ∗ ⌜ret == a⌝) ∨ (⌜c <u a⌝ ∗ ⌜b >=u a⌝ ∗ ⌜ret == a⌝) ∨ (⌜b <u a⌝ ∗ ⌜a <u b⌝) ∨ (⌜b >=u a⌝ ∗ ⌜b <u a⌝)'

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
log=$(go run ./gocheck -pkg ./checker/examples -post "$MEDIAN_POST" -rocq "$tmp" Median3)
echo "$log" | grep '^checker.Check:'
echo "$log" | grep -q '^checker.Check: true ' || { echo "observe.sh: checker.Check did not answer true" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
{
  echo "(* Generated by gocheck/observe.sh from"
  echo
  echo "     gocheck -pkg ./checker/examples -post <MEDIAN_POST> -rocq <file> Median3"
  echo
  echo "   with the postcondition of gocheck/demo.sh: the input gocheck hands to"
  echo "   checker.Check, which answered true. Do not edit. *)"
  echo "From New.checker Require Import prelude."
  echo
  cat "$tmp"
} > "$OUT"
echo "wrote $OUT"
