#!/usr/bin/env bash
# Records, as Lean definitions, the checker input gocheck builds for each of
# the six specifications of gocheck/demo.sh (gocheck/specs.sh), in
#
#   Checkers/Native/Inputs.lean
#
# Those are the inputs Checkers/Native/Examples.lean runs the Lean-native
# checker on (with native_decide). Unlike gocheck/observe.sh, nothing here is
# trusted: the Lean proofs check that each input's function is exactly
# Goose's translation (by rfl), so a wrong input fails to build rather than
# proving something false. gocheck's own verdict is printed for comparison.
#
# Run from the repository root: bash gocheck/native.sh
set -euo pipefail

if [ ! -d .lake/packages/perennial ]; then
	echo "missing .lake/packages/perennial (go.mod's replacement for perennial):" >&2
	echo "run 'lake build' first, which fetches the Lake dependencies" >&2
	exit 2
fi

. gocheck/specs.sh

OUT=Checkers/Native/Inputs.lean
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
go build -o "$tmp/gocheck" ./gocheck

# input NAME FUNC GOCHECK-ARGS... -- append NAME's definitions to $tmp/all
input() {
	local name=$1 fn=$2
	shift 2
	local log
	log=$("$tmp/gocheck" -pkg ./checker/examples "$@" -lean "$tmp/$name" -lean-name "$name" "$fn")
	echo "$fn: $(echo "$log" | grep '^checker.Check:')"
	cat "$tmp/$name" >>"$tmp/all"
	echo >>"$tmp/all"
}

: >"$tmp/all"
input double Double -pre "$DOUBLE_PRE" -post "$DOUBLE_POST"
input max Max -post "$MAX_POST"
input swap Swap -pre "$SWAP_PRE" -post "$SWAP_POST"
input abs Abs -post "$ABS_POST"
input condStore CondStore -pre "$CONDSTORE_PRE" -post "$CONDSTORE_POST"
input median3 Median3 -post "$MEDIAN_POST"

mkdir -p "$(dirname "$OUT")"
{
	echo "/- Generated by gocheck/native.sh from the six specifications of"
	echo "   gocheck/specs.sh: the inputs gocheck hands to checker.Check, as"
	echo "   Lean terms. Do not edit. -/"
	echo "import Checkers.Checker.Defs"
	echo
	echo "namespace Perennial"
	echo "namespace Checker"
	echo "namespace Native"
	echo
	cat "$tmp/all"
	echo "end Native"
	echo "end Checker"
	echo "end Perennial"
} >"$OUT"
echo "wrote $OUT"
